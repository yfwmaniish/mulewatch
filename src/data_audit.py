"""
Generates reports/data_audit.md from preprocess artifacts.

Run AFTER src.preprocess. Reads:
  data/processed/preprocess_report.json
  data/processed/dup_map.json
  data/processed/pre_split_crosstab.json
  data/processed/leakage_audit.json

Writes:
  reports/data_audit.md
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path


def render(processed_dir: Path, out_path: Path) -> None:
    report = json.loads((processed_dir / "preprocess_report.json").read_text())
    dup_map = json.loads((processed_dir / "dup_map.json").read_text())
    crosstab = json.loads((processed_dir / "pre_split_crosstab.json").read_text())
    leak = json.loads((processed_dir / "leakage_audit.json").read_text())

    raw_cols = report["raw_shape"][1]
    raw_rows = report["raw_shape"][0]
    final_cols = report["final_feature_count"]
    splits = report["splits"]
    f2230 = leak["step_a_f2230_collinear"]
    tgt = leak["step_b_target_collinear"]

    # -- Section 1: pipeline stages
    cols_after_basic = raw_cols - 2 - report["dropped_zero_variance"] - report["dropped_high_null"]
    cols_after_dedupe = cols_after_basic - report["dropped_duplicates"]

    # -- Section 2: largest duplicate groups
    biggest_groups = sorted(dup_map.items(), key=lambda kv: -len(kv[1]))[:5]
    biggest_lines = "\n".join(
        f"- keeper `{k}` → {len(v)} duplicates (e.g. `{', '.join(v[:5])}`{', ...' if len(v) > 5 else ''})"
        for k, v in biggest_groups
    ) or "_(none)_"

    # -- Section 3: pre-split cross-tab
    crosstab_sections = []
    for col, tbl in crosstab["tables"].items():
        if "skipped" in tbl:
            crosstab_sections.append(f"### `{col}`\n\n_{tbl['skipped']}_\n")
            continue
        rows = tbl["rows"]
        lines = ["| Category | Rows | Positives | Negatives | Target rate | Flag |",
                 "|---|---:|---:|---:|---:|---|"]
        for r in rows:
            flag = r.get("flag", "")
            lines.append(
                f"| `{r['category']}` | {r['rows']} | {r['positives']} | {r['negatives']} "
                f"| {r['target_rate']:.4f} | {flag} |"
            )
        flag_summary = ""
        if tbl.get("identity_flags"):
            flag_summary = f"\n**Identity flags:** `{col}` ∈ {{{', '.join(tbl['identity_flags'])}}} exactly matches the positive set.\n"
        crosstab_sections.append(f"### `{col}`\n\n" + "\n".join(lines) + flag_summary)
    crosstab_md = "\n\n".join(crosstab_sections)

    # -- Section 4a: F2230-collinear (auto-dropped)
    f2230_top = f2230["top_20_by_abs_corr"][:10]
    f2230_lines = "\n".join(
        f"| `{col}` | {corr:+.4f} | {'DROPPED' if abs(corr) > leak['threshold'] else 'kept'} |"
        for col, corr in f2230_top
    ) or "| _(no numeric cols scored)_ | | |"

    # -- Section 4b: target-collinear (flagged for manual audit)
    tgt_flagged = tgt["flagged_columns"]
    if tgt_flagged:
        tgt_lines_inner = "\n".join(
            f"| `{col}` | {corr:+.4f} | **AUDIT NEEDED** — {tgt['justifications'].get(col, 'TODO')} |"
            for col, corr in tgt_flagged
        )
        tgt_lines = (
            "| Column | corr with target | Justification (one line — fill before training) |\n"
            "|---|---:|---|\n" + tgt_lines_inner
        )
    else:
        tgt_lines = "_No features cross the |corr| > 0.95 threshold against the target after F2230-collinear drops. Clean._"

    md = f"""# Data Audit Report

Generated by `src/data_audit.py` from the latest `src.preprocess` run.

This document is the answer to "what other leakage paths exist?" — every leakage check we ran, every column dropped or flagged, and the rationale.

## 1. Pipeline stages

| Stage | Cols removed | Cols remaining |
|---|---:|---:|
| Raw input | — | {raw_cols} |
| Drop `Unnamed: 0` + target `F3924` | 2 | {raw_cols - 2} |
| Zero-variance | {report['dropped_zero_variance']} | {raw_cols - 2 - report['dropped_zero_variance']} |
| >{int(report['missing_threshold']*100)}% missing | {report['dropped_high_null']} | {cols_after_basic} |
| Exact-duplicate columns | {report['dropped_duplicates']} | {cols_after_dedupe} |
| F2230-collinearity (auto-drop) | {report['leakage_f2230_dropped']} | {final_cols} |
| Target-collinearity (flag, no auto-drop) | {report['leakage_target_flagged']} flagged | {final_cols} |

**Net feature reduction:** {raw_cols - 2} → **{final_cols}** ({(1 - final_cols / (raw_cols - 2)) * 100:.1f}% removed).

## 2. Duplicate-column audit

- **Groups found:** {report['duplicate_groups']}
- **Columns dropped:** {report['dropped_duplicates']}
- **Largest groups:**

{biggest_lines}

Full mapping in [`data/processed/dup_map.json`](../data/processed/dup_map.json).

## 3. Pre-split cross-tab (cardinality-coincidence check)

**Rule:** {crosstab.get('rule', '')}

This check is run **before any split or filter** so that exact identities between rare labels and rare categorical values get surfaced before they leak into modeling. Originally caught `F2230 ≡ target` (every non-Oct25 row is positive; cardinality match 81 ↔ 81).

{crosstab_md}

## 4. Leakage audit (two-step)

### 4a. F2230-collinearity — auto-drop ({f2230['dropped_count']} columns)

Pearson `|corr|` of each numeric column with the binary `non_oct25` indicator (1 if `F2230 != Oct25` else 0). Threshold: `|corr| > {leak['threshold']}`. Dropped unconditionally because these encode the snapshot-month leakage path.

**Top 10 columns by |corr|:**

| Column | corr with `non_oct25` | Action |
|---|---:|---|
{f2230_lines}

Full list in [`data/processed/leakage_audit.json`](../data/processed/leakage_audit.json) under `step_a_f2230_collinear`.

### 4b. Target-collinearity — flag for manual audit ({tgt['flagged_count']} columns)

After step 4a drops applied. Pearson `|corr|` of each remaining numeric column with the target `F3924`. Threshold: `|corr| > {leak['threshold']}`.

**Policy:** these are **not** auto-dropped. Each one is either (i) F2230-leakage we missed, (ii) the target column accidentally retained, or (iii) a legitimate near-perfect predictor (e.g., a "flagged by FMS" feature the bank already uses). Each needs a one-line justification before training.

{tgt_lines}

## 5. Final splits

| Split | Rows | Positives | Notes |
|---|---:|---:|---|
| Train (70%, target-stratified) | {splits['train']['rows']} | {splits['train']['positives']} | CV pool for hyperparameter tuning |
| Test (30%, target-stratified) | {splits['test']['rows']} | {splits['test']['positives']} | Holdout. Bootstrap 95% CI on metrics |
| Anomaly pool (L7D/L14D/L90D) | {splits['anomaly']['rows']} | {splits['anomaly']['positives']} | Zero-positive windows; unsupervised side-channel |

Raw rows in: **{raw_rows}**. Supervised pool (after anomaly filter): **{report['supervised_rows']}** ({report['supervised_positives']} positives).

## 6. Headline evaluation metrics

- **Headline:** Precision @ top-1% alerts — operational; matches analyst capacity.
- **Secondary:** PR-AUC with bootstrap 95% CI (1,000 resamples of the test set). The test set has {splits['test']['positives']} positives — bootstrap CI is the honest noise quantification.
- F2230 hard-excluded from features. Collinear cousins handled per section 4.

## 7. How to reproduce

```powershell
python -m src.preprocess --input DataSet.csv --out data/processed
python -m src.data_audit --processed data/processed --out reports/data_audit.md
```
"""
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(md, encoding="utf-8")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--processed", default="data/processed")
    ap.add_argument("--out", default="reports/data_audit.md")
    args = ap.parse_args()
    render(Path(args.processed), Path(args.out))
    print(f"Wrote {args.out}")


if __name__ == "__main__":
    main()
