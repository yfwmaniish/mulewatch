"""
FIU-IND Suspicious Transaction Report (STR) draft generator.

Produces a multi-page A4 PDF in the FIU-IND STR layout style, populated from:
  - Account demographic profile (real, from raw CSV)
  - Calibrated mule score + risk band
  - SHAP top-5 reasons rendered as natural-language compliance prose
  - Matched hard-block rules (I4C / CFCFRMS) if present

This is a DRAFT — every STR filed in production requires sign-off by a
designated Principal Officer. The bottom of every page makes this explicit.

Spec follows FIU-IND STR Form V2 field layout (publicly documented). Field
numbers and labels are illustrative, not regulatory text.
"""
from __future__ import annotations

import io
from datetime import datetime, timezone
from typing import Optional

from reportlab.lib import colors
from reportlab.lib.enums import TA_LEFT, TA_RIGHT
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.pdfgen import canvas
from reportlab.platypus import (
    BaseDocTemplate,
    Frame,
    KeepTogether,
    PageTemplate,
    Paragraph,
    Spacer,
    Table,
    TableStyle,
)


# --- color tokens ----------------------------------------------------------
NAVY = colors.HexColor("#0B2447")
EMERALD = colors.HexColor("#0F5132")
RED = colors.HexColor("#DC2626")
AMBER = colors.HexColor("#B45309")
SLATE = colors.HexColor("#334155")
MUTED = colors.HexColor("#64748B")
LIGHT = colors.HexColor("#F1F5F9")


# --- helpers ---------------------------------------------------------------
def _format_inr(amount: int | float | None) -> str:
    if amount is None:
        return "—"
    try:
        n = int(round(float(amount)))
    except Exception:
        return str(amount)
    s = str(abs(n))
    if len(s) <= 3:
        out = s
    else:
        head = s[:-3]
        tail = s[-3:]
        groups = []
        while len(head) > 2:
            groups.insert(0, head[-2:])
            head = head[:-2]
        if head:
            groups.insert(0, head)
        out = ",".join(groups) + "," + tail
    return f"INR {out}{'-' if n < 0 else ''}"


def _band_color(band: str):
    return {"HIGH": RED, "FREEZE": colors.HexColor("#A21CAF"), "MEDIUM": AMBER, "LOW": EMERALD}.get(band, MUTED)


# --- page chrome -----------------------------------------------------------
def _on_page(canv: canvas.Canvas, doc) -> None:
    width, height = A4
    # Top band
    canv.setFillColor(NAVY)
    canv.rect(0, height - 18 * mm, width, 18 * mm, stroke=0, fill=1)
    canv.setFillColor(colors.white)
    canv.setFont("Helvetica-Bold", 11)
    canv.drawString(15 * mm, height - 10 * mm, "FINANCIAL INTELLIGENCE UNIT — INDIA")
    canv.setFont("Helvetica", 8)
    canv.drawString(15 * mm, height - 14 * mm,
                    "Suspicious Transaction Report (STR)  ·  Form V2  ·  AI-assisted draft")
    canv.setFont("Helvetica-Bold", 9)
    canv.drawRightString(width - 15 * mm, height - 10 * mm, "DRAFT — NOT FILED")
    canv.setFont("Helvetica", 8)
    canv.drawRightString(width - 15 * mm, height - 14 * mm,
                         datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC"))

    # Bottom footer
    canv.setStrokeColor(NAVY)
    canv.setLineWidth(0.6)
    canv.line(15 * mm, 17 * mm, width - 15 * mm, 17 * mm)
    canv.setFillColor(SLATE)
    canv.setFont("Helvetica", 7)
    canv.drawString(
        15 * mm, 12 * mm,
        "Draft generated by the MuleWatch scoring service. Principal Officer review and digital signature required prior to FIU-IND filing.",
    )
    canv.drawRightString(width - 15 * mm, 12 * mm, f"Page {canv.getPageNumber()}")


# --- public API ------------------------------------------------------------
def build_str_pdf(
    account_id: int,
    display_id: str,
    customer_name: str,
    kyc_status: str,
    score: float,
    band: str,
    action: str,
    matched_rules: list[str],
    top_reasons: list[dict],
    profile: dict,
    model_version: str,
    counterparties: Optional[list[dict]] = None,
    analyst_id: str = "(analyst pending)",
) -> bytes:
    """Render the STR draft to PDF bytes."""
    buf = io.BytesIO()
    styles = getSampleStyleSheet()

    h_style = ParagraphStyle(
        "h", parent=styles["Heading2"], textColor=NAVY,
        fontName="Helvetica-Bold", fontSize=11, spaceAfter=4, leading=14,
    )
    h_label = ParagraphStyle(
        "label", parent=styles["BodyText"], textColor=MUTED,
        fontName="Helvetica-Bold", fontSize=7, leading=9, spaceAfter=1,
        alignment=TA_LEFT,
    )
    body = ParagraphStyle(
        "body", parent=styles["BodyText"], textColor=SLATE,
        fontName="Helvetica", fontSize=9, leading=12, spaceAfter=2,
    )
    body_bold = ParagraphStyle(
        "bodyb", parent=body, fontName="Helvetica-Bold", textColor=NAVY,
    )
    small = ParagraphStyle(
        "sm", parent=styles["BodyText"], textColor=MUTED,
        fontName="Helvetica", fontSize=8, leading=10,
    )

    doc = BaseDocTemplate(
        buf, pagesize=A4,
        leftMargin=15 * mm, rightMargin=15 * mm,
        topMargin=24 * mm, bottomMargin=20 * mm,
        title=f"STR Draft · {display_id}",
        author="MuleWatch AML Compliance Core",
    )
    frame = Frame(
        doc.leftMargin, doc.bottomMargin,
        doc.width, doc.height, id="main", showBoundary=0,
    )
    doc.addPageTemplates([PageTemplate(id="default", frames=[frame], onPage=_on_page)])

    story: list = []

    # Filing reference header
    ref = matched_rules[0] if matched_rules else f"INTL-STR-{account_id:05d}"
    story.append(Paragraph(f"Filing reference: <b>{ref}</b>", body_bold))
    story.append(Paragraph(
        f"Source institution: <b>Indian Bank — PSB Branch (Demo)</b>   "
        f"Model version: <b>{model_version[:8]}</b>",
        small,
    ))
    story.append(Spacer(1, 6))

    # Risk banner
    banner_color = _band_color(band)
    risk_tbl = Table(
        [[
            Paragraph(f"<b>Risk band: {band}</b>", ParagraphStyle("rb", textColor=colors.white, fontName="Helvetica-Bold", fontSize=12, alignment=TA_LEFT)),
            Paragraph(f"Calibrated probability: <b>{score:.3f}</b>", ParagraphStyle("rs", textColor=colors.white, fontName="Helvetica", fontSize=10, alignment=TA_RIGHT)),
            Paragraph(f"Recommended action: <b>{action}</b>", ParagraphStyle("ra", textColor=colors.white, fontName="Helvetica", fontSize=10, alignment=TA_RIGHT)),
        ]],
        colWidths=[55 * mm, 60 * mm, 65 * mm],
    )
    risk_tbl.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), banner_color),
        ("LEFTPADDING", (0, 0), (-1, -1), 8),
        ("RIGHTPADDING", (0, 0), (-1, -1), 8),
        ("TOPPADDING", (0, 0), (-1, -1), 6),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
        ("ROUNDEDCORNERS", (0, 0), (-1, -1), [3, 3, 3, 3]),
    ]))
    story.append(risk_tbl)
    story.append(Spacer(1, 10))

    # Section 1 — Reporting Entity / Account
    story.append(Paragraph("1. Reporting entity &amp; subject account", h_style))
    rows = [
        ["Account display ID",       display_id],
        ["Internal account number",   f"INT-{account_id:05d}"],
        ["Customer name",             customer_name],
        ["KYC status",                kyc_status],
        ["Account type",              profile.get("account_type") or "—"],
        ["Customer segment",          profile.get("segment") or "—"],
        ["Occupation",                profile.get("occupation") or "—"],
        ["Region",                    {"M": "Metro", "R": "Rural", "SU": "Semi-Urban", "U": "Urban"}.get(profile.get("region") or "", profile.get("region") or "—")],
        ["Date account opened",       profile.get("account_opened") or "—"],
        ["Aggregation window",        profile.get("time_window") or "—"],
    ]
    tbl = Table(rows, colWidths=[55 * mm, 125 * mm])
    tbl.setStyle(TableStyle([
        ("FONTNAME", (0, 0), (0, -1), "Helvetica-Bold"),
        ("FONTNAME", (1, 0), (1, -1), "Helvetica"),
        ("FONTSIZE", (0, 0), (-1, -1), 9),
        ("TEXTCOLOR", (0, 0), (0, -1), MUTED),
        ("TEXTCOLOR", (1, 0), (1, -1), SLATE),
        ("BACKGROUND", (0, 0), (-1, -1), LIGHT),
        ("ROWBACKGROUNDS", (0, 0), (-1, -1), [LIGHT, colors.white]),
        ("BOX", (0, 0), (-1, -1), 0.4, colors.HexColor("#CBD5E1")),
        ("INNERGRID", (0, 0), (-1, -1), 0.3, colors.HexColor("#E2E8F0")),
        ("LEFTPADDING", (0, 0), (-1, -1), 7),
        ("RIGHTPADDING", (0, 0), (-1, -1), 7),
        ("TOPPADDING", (0, 0), (-1, -1), 4),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
    ]))
    story.append(tbl)
    story.append(Spacer(1, 10))

    # Section 2 — Suspicious-activity narrative
    story.append(Paragraph("2. Suspicious-activity narrative (model-generated)", h_style))
    pos_reasons = [r for r in top_reasons if r.get("shap", 0) > 0][:3]
    if pos_reasons:
        bullets = " ".join(
            f"({i+1}) <b>{r['feature']}</b> — {r['humanDescription'] if 'humanDescription' in r else 'plausible mule-pattern behaviour'}."
            for i, r in enumerate(pos_reasons)
        )
        narrative = (
            f"Account {display_id} was scored at calibrated probability "
            f"<b>{score:.3f}</b> by the MuleWatch model (version {model_version[:8]}), "
            f"placing it in the <b>{band}</b> risk band. Top contributors to the score: {bullets} "
            f"This combination of behavioural signals is consistent with "
            f"{'pass-through mule account activity' if band in ('HIGH', 'FREEZE') else 'low-confidence anomalous behaviour'}; "
            f"recommended action is <b>{action}</b>."
        )
    else:
        narrative = (
            f"Account {display_id} scored at {score:.3f} ({band}). "
            f"Recommended action: {action}. See Section 3 for SHAP attribution detail."
        )
    story.append(Paragraph(narrative, body))
    story.append(Spacer(1, 8))

    # Section 3 — SHAP attributions table
    story.append(Paragraph("3. Model attribution (SHAP) — top 5 contributors", h_style))
    shap_rows = [["Rank", "Feature", "SHAP value", "Direction", "Interpretation"]]
    for i, r in enumerate(top_reasons[:5], 1):
        shap = float(r.get("shap", r.get("contribution", 0.0)))
        direction = "↑ mule risk" if shap > 0 else "↓ mule risk"
        desc = r.get("humanDescription") or r.get("description") or "Behavioural feature contribution"
        # truncate long descriptions
        if len(desc) > 110:
            desc = desc[:107] + "…"
        shap_rows.append([
            str(i),
            r.get("feature", "—"),
            f"{shap:+.3f}",
            direction,
            desc,
        ])
    shap_tbl = Table(shap_rows, colWidths=[10 * mm, 20 * mm, 22 * mm, 25 * mm, 103 * mm])
    shap_tbl.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), NAVY),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, -1), 8),
        ("FONTNAME", (0, 1), (-1, -1), "Helvetica"),
        ("FONTNAME", (1, 1), (1, -1), "Courier-Bold"),
        ("TEXTCOLOR", (0, 1), (-1, -1), SLATE),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, LIGHT]),
        ("BOX", (0, 0), (-1, -1), 0.4, colors.HexColor("#CBD5E1")),
        ("INNERGRID", (0, 0), (-1, -1), 0.3, colors.HexColor("#E2E8F0")),
        ("LEFTPADDING", (0, 0), (-1, -1), 5),
        ("RIGHTPADDING", (0, 0), (-1, -1), 5),
        ("TOPPADDING", (0, 0), (-1, -1), 4),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
        ("ALIGN", (0, 0), (3, -1), "LEFT"),
    ]))
    story.append(shap_tbl)
    story.append(Spacer(1, 8))

    # Section 4 — Matched hard-block rules
    story.append(Paragraph("4. Matched regulatory feeds &amp; hard-block rules", h_style))
    if matched_rules:
        for r in matched_rules:
            story.append(Paragraph(
                f"<b>•</b>&nbsp;&nbsp;{r}  <i>(I4C / CFCFRMS / FIU-IND watchlist match — automatic freeze authorised)</i>",
                body,
            ))
    else:
        story.append(Paragraph("No regulatory hard-block rules matched at the time of filing. Score-driven action only.", body))
    story.append(Spacer(1, 8))

    # Section 5 — Counterparties (synthesized footnote)
    story.append(Paragraph("5. Counterparty ledger snapshot", h_style))
    if counterparties:
        cp_rows = [["Counterparty", "Channel", "Amount", "Time"]]
        for cp in counterparties[:6]:
            cp_rows.append([
                cp.get("name", "—"),
                cp.get("channel", "—"),
                _format_inr(cp.get("amount")),
                cp.get("timestamp") or "—",
            ])
        cp_tbl = Table(cp_rows, colWidths=[60 * mm, 25 * mm, 45 * mm, 50 * mm])
        cp_tbl.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), EMERALD),
            ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
            ("FONTSIZE", (0, 0), (-1, -1), 8),
            ("TEXTCOLOR", (0, 1), (-1, -1), SLATE),
            ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, LIGHT]),
            ("BOX", (0, 0), (-1, -1), 0.4, colors.HexColor("#CBD5E1")),
            ("INNERGRID", (0, 0), (-1, -1), 0.3, colors.HexColor("#E2E8F0")),
            ("LEFTPADDING", (0, 0), (-1, -1), 5),
            ("RIGHTPADDING", (0, 0), (-1, -1), 5),
            ("TOPPADDING", (0, 0), (-1, -1), 3),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
        ]))
        story.append(cp_tbl)
        story.append(Paragraph(
            "Counterparty ledger above is synthesized for visualization. The supplied dataset is anonymised "
            "and does not include transaction-edge data; production STR filings draw counterparty rows from "
            "the core banking system's transaction store.",
            small,
        ))
    else:
        story.append(Paragraph("Counterparty ledger not available for this account (anonymised dataset).", small))
    story.append(Spacer(1, 10))

    # Section 6 — Sign-off block
    story.append(Paragraph("6. Compliance sign-off", h_style))
    sign_rows = [
        ["Prepared by",   f"MuleWatch automated draft · {datetime.now(timezone.utc).strftime('%Y-%m-%d')}"],
        ["Analyst",       analyst_id],
        ["Principal Officer (FIU-IND)", "(signature required)"],
        ["Date of intended filing", "(to be confirmed by Principal Officer)"],
    ]
    sign_tbl = Table(sign_rows, colWidths=[55 * mm, 125 * mm])
    sign_tbl.setStyle(TableStyle([
        ("FONTNAME", (0, 0), (0, -1), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, -1), 9),
        ("TEXTCOLOR", (0, 0), (0, -1), MUTED),
        ("TEXTCOLOR", (1, 0), (1, -1), SLATE),
        ("BACKGROUND", (0, 0), (-1, -1), colors.white),
        ("BOX", (0, 0), (-1, -1), 0.6, NAVY),
        ("INNERGRID", (0, 0), (-1, -1), 0.3, colors.HexColor("#E2E8F0")),
        ("LEFTPADDING", (0, 0), (-1, -1), 7),
        ("RIGHTPADDING", (0, 0), (-1, -1), 7),
        ("TOPPADDING", (0, 0), (-1, -1), 6),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
    ]))
    story.append(KeepTogether(sign_tbl))

    doc.build(story)
    return buf.getvalue()
