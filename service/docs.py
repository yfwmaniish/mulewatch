def _render(title: str, md_text: str) -> bytes:
    html_body = md.markdown(md_text, extensions=["tables", "fenced_code", "nl2br"])
    full_html = f"""<!DOCTYPE html>
<html><head><meta charset="utf-8"><title>{title}</title><style>{_CSS}</style></head>
<body>
  <div class="header-bar">
    <div class="title">MuleWatch · AML Compliance Core</div>
    <div class="sub">Auto-generated document · PSB IIT Hyderabad submission</div>
  </div>
  <div id="footerContent" class="footer">
    Generated by MuleWatch scoring service · <pdf:pagenumber/> / <pdf:pagecount/>
  </div>
  {html_body}
</body></html>
"""
    out = io.BytesIO()
    pisa_status = pisa.CreatePDF(src=full_html, dest=out, encoding="utf-8")
    if pisa_status.err:
        raise RuntimeError(f"PDF generation failed: {pisa_status.err}")
    return out.getvalue()


def render_pdf(slug: str, root: Path) -> Optional[tuple[bytes, str]]:
    """Return (pdf_bytes, filename) for the given slug, or None if not configured."""
    if slug not in DOCS:
        return None
    rel_path, title, filename = DOCS[slug]
    src = root / rel_path
    if not src.exists():
        return None
    if slug in _PDF_CACHE:
        return _PDF_CACHE[slug], filename
    md_text = src.read_text(encoding="utf-8")
    pdf_bytes = _render(title, md_text)
    _PDF_CACHE[slug] = pdf_bytes
    return pdf_bytes, filename


def list_docs() -> list[dict]:
    return [
        {"slug": slug, "title": title, "filename": filename, "path": path}
        for slug, (path, title, filename) in DOCS.items()
    ]
