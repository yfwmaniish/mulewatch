"""
Convert any of the reports/*.md files into a styled, downloadable PDF.

Used by the analyst console's "Download Model Card" / "Download Audit Report"
buttons. PDF is generated on demand, cached in process memory.
"""
from __future__ import annotations

import io
from pathlib import Path
from typing import Optional

import markdown as md
from xhtml2pdf import pisa


# Slug → (markdown file path, friendly title, PDF download filename)
DOCS: dict[str, tuple[str, str, str]] = {
    "model-card":      ("reports/model_card.md",        "Mule Detection · Model Card",          "MuleWatch_Model_Card.pdf"),
    "audit-report":    ("reports/data_audit.md",        "Mule Detection · Data Audit",          "MuleWatch_Data_Audit.pdf"),
    "final-report":    ("reports/final_report.md",      "Mule Detection · Final Submission",    "MuleWatch_Final_Report.pdf"),
    "model-results":   ("reports/model_results.md",     "Mule Detection · Model Results",       "MuleWatch_Model_Results.pdf"),
    "calibration":     ("reports/calibration.md",       "Mule Detection · Calibration",         "MuleWatch_Calibration.pdf"),
    "feature-semantics":("reports/feature_semantics.md","Mule Detection · Feature Semantics",   "MuleWatch_Feature_Semantics.pdf"),
    "feature-selection":("reports/feature_selection.md","Mule Detection · Feature Selection",   "MuleWatch_Feature_Selection.pdf"),
    "cv-variance":     ("reports/cv_variance.md",       "Mule Detection · CV Variance",         "MuleWatch_CV_Variance.pdf"),
    "latency":         ("reports/latency_benchmark.md", "Mule Detection · Latency Benchmark",   "MuleWatch_Latency_Benchmark.pdf"),
}

