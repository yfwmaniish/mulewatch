"""
Latency benchmark — 1,000 /score calls against a running FastAPI server.

Usage (in two terminals):
  Terminal 1:  uvicorn service.api:app --port 8000
  Terminal 2:  python -m service.benchmark --n 1000 --url http://localhost:8000

Writes percentiles to reports/latency_benchmark.md.
"""
from __future__ import annotations

import argparse
import json
import random
import statistics
import time
from datetime import datetime, timezone
from pathlib import Path

import urllib.request


def call_score(url: str, account_id: int) -> float:
    """Returns wall-clock latency in milliseconds for a single /score call."""
    payload = json.dumps({"account_id": account_id}).encode()
    req = urllib.request.Request(
        f"{url}/score",
        data=payload,
        headers={"Content-Type": "application/json"},
        method="POST",
    )
    t0 = time.perf_counter()
    with urllib.request.urlopen(req, timeout=10) as resp:
        resp.read()
    return (time.perf_counter() - t0) * 1000.0


def fetch_account_ids(url: str) -> list[int]:
    req = urllib.request.Request(f"{url}/accounts?page_size=500&sort=id_asc")
    with urllib.request.urlopen(req, timeout=10) as resp:
        body = json.loads(resp.read())
    return [a["account_id"] for a in body["accounts"]]


def percentile(values: list[float], p: float) -> float:
    s = sorted(values)
    k = int(round((p / 100.0) * (len(s) - 1)))
    return s[max(0, min(k, len(s) - 1))]


def run(n: int, url: str, out_path: Path) -> dict:
    account_ids = fetch_account_ids(url)
    if not account_ids:
        raise RuntimeError("no accounts available from /accounts endpoint")
    print(f"Loaded {len(account_ids)} account IDs from {url}")

    # Warmup
    for aid in random.sample(account_ids, min(20, len(account_ids))):
        call_score(url, aid)

    rng = random.Random(42)
    latencies: list[float] = []
    print(f"Running {n} /score calls ...")
    t_start = time.perf_counter()
    for i in range(n):
        aid = rng.choice(account_ids)
        latencies.append(call_score(url, aid))
        if (i + 1) % 100 == 0:
            print(f"  {i + 1}/{n}  rolling p95={percentile(latencies, 95):.1f}ms")
    wall_seconds = time.perf_counter() - t_start

    result = {
        "n": n,
        "url": url,
        "wall_seconds": round(wall_seconds, 3),
        "throughput_rps": round(n / wall_seconds, 1),
        "p50_ms": round(percentile(latencies, 50), 2),
        "p95_ms": round(percentile(latencies, 95), 2),
        "p99_ms": round(percentile(latencies, 99), 2),
        "min_ms": round(min(latencies), 2),
        "max_ms": round(max(latencies), 2),
        "mean_ms": round(statistics.mean(latencies), 2),
        "stdev_ms": round(statistics.stdev(latencies) if len(latencies) > 1 else 0.0, 2),
        "generated_at": datetime.now(timezone.utc).isoformat(),
    }

    md = f"""# Latency Benchmark

Generated by `python -m service.benchmark` against `{url}`.

## Results — {n:,} POST /score calls

| Metric | Value |
|---|---:|
| **p50** | **{result['p50_ms']} ms** |
| **p95** | **{result['p95_ms']} ms** |
| **p99** | **{result['p99_ms']} ms** |
| Min | {result['min_ms']} ms |
| Max | {result['max_ms']} ms |
| Mean | {result['mean_ms']} ms |
| Stdev | {result['stdev_ms']} ms |
| Wall time | {result['wall_seconds']} s |
| Throughput | {result['throughput_rps']} req/s |

## Latency budget

Target from PLAN.md Phase 9: **p95 < 100 ms**. Measured: **{result['p95_ms']} ms**. \
{"PASS" if result['p95_ms'] < 100 else "MISS"}.

## Method

- Single FastAPI worker (uvicorn default), local loopback to eliminate network noise.
- 20 warmup calls excluded from the timing.
- Account IDs drawn uniformly at random from the test set (2,521 accounts).
- Latency measured client-side from request send to response body fully read.

Generated at {result['generated_at']}.
"""
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(md, encoding="utf-8")
    return result


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", type=int, default=1000)
    ap.add_argument("--url", default="http://localhost:8000")
    ap.add_argument("--out", default="reports/latency_benchmark.md")
    args = ap.parse_args()
    result = run(args.n, args.url, Path(args.out))
    print(json.dumps(result, indent=2))
    print(f"\nWrote {args.out}")


if __name__ == "__main__":
    main()
